#!/usr/bin/env node
// Generates the Windows-to-IANA zone table for ICS feeds (docs/architecture.md §7.7) from the
// Unicode CLDR file `windowsZones.xml`, using the default territory (`001`) row of each zone.
//
//   node scripts/windows-zones.mjs [cldr-tag]
//
// The tag is a release tag of github.com/unicode-org/cldr; the default is the one the checked-in
// table was made from. The output replaces src-tauri/crates/core/src/provider/ics/windows_zones.rs.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const tag = process.argv[2] ?? 'release-48-2';
const url = `https://raw.githubusercontent.com/unicode-org/cldr/${tag}/common/supplemental/windowsZones.xml`;
const out = fileURLToPath(
	new URL('../src-tauri/crates/core/src/provider/ics/windows_zones.rs', import.meta.url)
);

const response = await fetch(url);
if (!response.ok) {
	console.error(`${url}: HTTP ${response.status}`);
	process.exit(1);
}
const xml = await response.text();

// Every row looks like <mapZone other="W. Europe Standard Time" territory="001" type="Europe/Berlin"/>.
const rows = [];
for (const [, attrs] of xml.matchAll(/<mapZone\s+([^>]*?)\/?>/g)) {
	const attr = (name) => attrs.match(new RegExp(`${name}="([^"]*)"`))?.[1];
	if (attr('territory') === '001') rows.push([attr('other'), attr('type')]);
}
if (rows.length < 100) {
	console.error(`only ${rows.length} rows found; has the file format changed?`);
	process.exit(1);
}
rows.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const lines = [
	'//! Windows zone names to IANA zones, for `TZID`s written by Outlook and Exchange',
	'//! (`docs/architecture.md` §7.7). Generated by `scripts/windows-zones.mjs`: do not edit.',
	'//!',
	`//! Source: Unicode CLDR \`${tag}\`, \`common/supplemental/windowsZones.xml\`, territory \`001\`.`,
	'',
	'/// `(Windows name, IANA name)`, sorted by Windows name.',
	'pub(super) const WINDOWS_ZONES: &[(&str, &str)] = &[',
	...rows.map(([windows, iana]) => `    (${JSON.stringify(windows)}, ${JSON.stringify(iana)}),`),
	'];',
	''
];
writeFileSync(out, lines.join('\n'));
console.log(`${rows.length} zones from CLDR ${tag} written to ${out}`);
